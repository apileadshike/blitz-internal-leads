import { BlitzAPI } from "blitz-api-js";
process.loadEnvFile(".env");
const c = new BlitzAPI({ api_key: process.env.BLITZ_API_KEY });
const f = { company:{ industry:{include:["Software Development"]}, hq:{country_code:["DE"]}}, people:{ job_level:["C-Team"] } };
const p1 = await c.search.people({ ...f, max_results: 2 });
const cur = p1.response.cursor;
console.log("cursor:", cur, "| decoded:", (()=>{try{return Buffer.from(cur,"base64").toString()}catch{return "-"}})().slice(0,200));
const a = await c.search.people({ ...f, max_results: 2, cursor: cur });
await new Promise(r=>setTimeout(r, 20000));
const b = await c.search.people({ ...f, max_results: 2, cursor: cur });
console.log("page2 now  :", a.data.map(x=>x.linkedin_url).join(" "));
console.log("page2 +20s :", b.data.map(x=>x.linkedin_url).join(" "));
const c2 = await c.search.people({ ...f, max_results: 3, cursor: cur });
console.log("diff size  :", c2.data.map(x=>x.linkedin_url).join(" "));
